/**
 * Independent, defensive inspector for the STORED ZIP archives emitted by
 * src/xlsx.mjs. No dependency on the production ZIP writer or XML serializer.
 * An archive produced by another program using compression is rejected rather
 * than partially interpreted as a passing UAT file.
 *
 * This module validates the actual *output bytes*, not target app acceptance.
 */
import {isDeepStrictEqual} from 'node:util';
import {isoDate,toMinorUnits,fromMinorUnits,validateQuickBooksCSVParts} from '../src/core.mjs';

function insist(ok,reason){if(!ok)throw Error(reason);}
// Preserve a leading UTF-8 BOM: QuickBooks CSV part byte counts include it.
// TextDecoder's default strips BOM, which would hide three original bytes.
const td=new TextDecoder('utf-8',{fatal:true,ignoreBOM:true});
const crcTable=Uint32Array.from({length:256},(_,index)=>{
  let n=index;
  for(let i=0;i<8;i++)n=(n>>>1)^(0xedb88320&-(n&1));
  return n>>>0;
});
function crc32(bytes){
  let n=0xffffffff;
  for(const byte of bytes)n=crcTable[(n^byte)&255]^(n>>>8);
  return (n^0xffffffff)>>>0;
}
const zipSafeName=name=>/^[a-zA-Z0-9_\-./\[\]]{1,200}$/.test(name)&&
  !name.includes('..')&&!name.startsWith('/')&&!name.endsWith('/');
function textValue(bytes){
  const value=td.decode(bytes);
  insist(!value.includes('\u0000'),'Archive entry contains null bytes');
  return value;
}
export function inspectStoredArchive(data,{maxBytes=32*1024*1024,maxEntries=80}={}){
  const b=Buffer.from(data??[]);
  insist(b.length>=22&&b.length<=maxBytes,'Archive size exceeds private checker limits');
  const u16=(i)=>{insist(i>=0&&i+2<=b.length,'Archive truncated field');return b.readUInt16LE(i);};
  const u32=(i)=>{insist(i>=0&&i+4<=b.length,'Archive truncated field');return b.readUInt32LE(i);};
  let end=-1;
  // Only exact, trailing-comment-free ZIPs generated by this application's writer.
  if(u32(b.length-22)===0x06054b50&&u16(b.length-2)===0)end=b.length-22;
  insist(end>=0,'Missing canonical ZIP end-of-directory');
  insist(u16(end+4)===0&&u16(end+6)===0,'Multi-volume archives unsupported');
  const count=u16(end+10);
  insist(count===u16(end+8)&&count>0&&count<=maxEntries,'Archive entry count mismatch');
  const centralSize=u32(end+12),centralStart=u32(end+16);
  insist(centralStart+centralSize===end,'Central directory length or offset mismatch');
  const entries=new Map();
  const spans=[];
  let pos=centralStart;
  for(let i=0;i<count;i++){
    insist(u32(pos)===0x02014b50,'Central ZIP header missing');
    const flags=u16(pos+8),compression=u16(pos+10),crc=u32(pos+16);
    const packed=u32(pos+20),unpacked=u32(pos+24);
    const nameLen=u16(pos+28),extraLen=u16(pos+30),commentLen=u16(pos+32);
    const disk=u16(pos+34),localOffset=u32(pos+42);
    insist(flags===0&&compression===0&&packed===unpacked&&disk===0,'Unsupported compressed, encrypted, split or descriptor ZIP');
    insist(pos+46+nameLen+extraLen+commentLen<=end,'ZIP central entry out of range');
    const name=textValue(b.subarray(pos+46,pos+46+nameLen));
    insist(zipSafeName(name)&&!entries.has(name),'Unsafe or duplicate ZIP entry');
    insist(localOffset+30<=centralStart&&u32(localOffset)===0x04034b50,'ZIP local header missing');
    insist(u16(localOffset+6)===flags&&u16(localOffset+8)===compression,'ZIP local flags mismatch');
    insist(u32(localOffset+14)===crc&&u32(localOffset+18)===packed&&u32(localOffset+22)===unpacked,'ZIP central/local sizes or CRC disagree');
    const localNameLen=u16(localOffset+26),localExtraLen=u16(localOffset+28);
    insist(localNameLen===nameLen,'ZIP names differ in local/central directories');
    insist(textValue(b.subarray(localOffset+30,localOffset+30+nameLen))===name,'ZIP local filename mismatch');
    const start=localOffset+30+localNameLen+localExtraLen;
    insist(start+packed<=centralStart,'ZIP local data overruns archive body');
    const raw=b.subarray(start,start+packed);
    insist(crc32(raw)===crc,'ZIP CRC checksum mismatch');
    spans.push([localOffset,start+packed]);
    entries.set(name,Buffer.from(raw));
    pos+=46+nameLen+extraLen+commentLen;
  }
  insist(pos===end,'Trailing central ZIP metadata or truncated directory');
  spans.sort((a,b)=>a[0]-b[0]);
  insist(spans[0][0]===0,'Unrecognized prefix before ZIP data');
  for(let i=1;i<spans.length;i++)insist(spans[i][0]===spans[i-1][1],'Overlapping or concealed ZIP payload');
  insist(spans.at(-1)[1]===centralStart,'Unexpected bytes before ZIP directory');
  return entries;
}
function xmlEntities(text){
  return text.replace(/&(#(?:x[0-9a-fA-F]+|[0-9]+)|[a-zA-Z]+);/g,(_,token)=>{
    const named={amp:'&',lt:'<',gt:'>',quot:'"',apos:"'"};
    if(Object.hasOwn(named,token))return named[token];
    insist(token.startsWith('#'),'Unexpected XML entity');
    const code=token[1]==='x'?Number.parseInt(token.slice(2),16):Number(token.slice(1));
    insist(Number.isInteger(code)&&code>=1&&code<=0x10ffff&&
      !(code>=0xd800&&code<=0xdfff),'Invalid XML numeric character entity');
    return String.fromCodePoint(code);
  });
}
function decodeInline(cell,location){
  const found=cell.match(/^<is><t(?: xml:space="preserve")?>([\s\S]*?)<\/t><\/is>$/);
  insist(Boolean(found),'Missing/unsupported inline text at '+location);
  const inner=found[1];
  insist(!/&(?!(?:#(?:x[0-9a-fA-F]+|[0-9]+)|[a-zA-Z]+);)/.test(inner),'Invalid XML escaping at '+location);
  return xmlEntities(inner);
}
const cellPattern=/<c r="([A-E]\d+)"([^>]*)>([\s\S]*?)<\/c>/g;
function serial(date){
  const value=isoDate(date);
  const [y,m,d]=value.split('-').map(Number);
  const days=(Date.UTC(y,m-1,d)-Date.UTC(1899,11,31))/86400000;
  return String(days+(value>='1900-03-01'?1:0));
}
function money(n){return fromMinorUnits(toMinorUnits(n));}
export function inspectExactXLSX(data,source){
  insist(Array.isArray(source)&&source.length>0,'Original parsed transactions required for XLSX verification');
  const entries=inspectStoredArchive(data);
  const needed=['[Content_Types].xml','_rels/.rels','xl/workbook.xml','xl/_rels/workbook.xml.rels','xl/styles.xml','xl/worksheets/sheet1.xml'];
  insist(entries.size===needed.length&&needed.every(k=>entries.has(k)),'XLSX parts are missing or unexpected');
  const workbook=textValue(entries.get('xl/workbook.xml'));
  const styles=textValue(entries.get('xl/styles.xml'));
  const sheet=textValue(entries.get('xl/worksheets/sheet1.xml'));
  insist(/<workbookPr date1904="0"\/>/.test(workbook),'Unexpected Excel date system');
  insist(/<numFmt numFmtId="164" formatCode="yyyy-mm-dd"\/>/.test(styles),'Date number format missing');
  insist(/<xf numFmtId="2" xfId="0" applyNumberFormat="1"\/>/.test(styles),'Amount numeric style missing');
  insist(/<xf numFmtId="164" xfId="0" applyNumberFormat="1"\/>/.test(styles),'Date numeric style missing');
  insist(!/<f(?:\s|>)/.test(sheet),'Excel workbook unexpectedly contains formulas');
  const srcRows=sheet.match(/<sheetData>([\s\S]*?)<\/sheetData>/);
  insist(Boolean(srcRows),'XLSX worksheet has no supported sheetData');
  const rows=[...srcRows[1].matchAll(/<row r="(\d+)">([\s\S]*?)<\/row>/g)];
  insist(rows.length===source.length+1,'XLSX row count differs from source');
  insist(srcRows[1].replace(/<row r="\d+">[\s\S]*?<\/row>/g,'')==='','Unexpected XML between data rows');
  const all=rows.map((match,rowIdx)=>{
    insist(Number(match[1])===rowIdx+1,'XLSX row numbering changed');
    const cells=[...match[2].matchAll(cellPattern)];
    insist([4,5].includes(cells.length),'Unsupported XLSX column count at row '+(rowIdx+1));
    insist(cells.every((cell,i)=>cell[1]===String.fromCharCode(65+i)+(rowIdx+1)),'XLSX columns reordered or missing');
    insist(match[2].replace(cellPattern,'')==='','Unexpected XML or cells in XLSX row');
    return cells;
  });
  const memo=all[0].length===5;
  insist(all.every(r=>r.length===(memo?5:4)),'Inconsistent XLSX column count');
  const head=['Date','Description','Amount','Reference',...(memo?['Memo']:[])];
  for(let i=0;i<head.length;i++){
    const c=all[0][i];
    insist(c[2]===' t="inlineStr"','Wrong Excel header cell type');
    insist(decodeInline(c[3],'header')===head[i],'Wrong XLSX header text');
  }
  const hasMemo=source.some(t=>String(t.memo??'').length>0);
  insist(!hasMemo||memo,'Source Memo omitted from XLSX: select Include Memo');
  let net=0n;
  for(let i=0;i<source.length;i++){
    const cells=all[i+1],tx=source[i],row=i+2;
    const d=cells[0],name=cells[1],amount=cells[2],ref=cells[3];
    const date=d[3].match(/^<v>(\d+)<\/v>$/);
    insist(d[2]===' s="2"'&&Boolean(date)&&date[1]===serial(tx.date),'XLSX row '+row+': date changed');
    insist(name[2]===' t="inlineStr"'&&decodeInline(name[3],'B'+row)===String(tx.description??''),'XLSX row '+row+': description changed');
    const val=amount[3].match(/^<v>(-?\d+(?:\.\d{1,2})?)<\/v>$/);
    insist(amount[2]===' s="1"'&&Boolean(val),'XLSX row '+row+': numeric cents changed');
    insist(money(val[1])===money(tx.amount),'XLSX row '+row+': signed cents changed');
    insist(ref[2]===' t="inlineStr"'&&decodeInline(ref[3],'D'+row)===String(tx.id??''),'XLSX row '+row+': reference changed');
    if(memo)insist(cells[4][2]===' t="inlineStr"'&&decodeInline(cells[4][3],'E'+row)===String(tx.memo??''),'XLSX row '+row+': Memo changed');
    net+=toMinorUnits(val[1]);
  }
  insist(net===source.reduce((n,t)=>n+toMinorUnits(t.amount),0n),'XLSX net signed cents changed');
  const range='A1:'+(memo?'E':'D')+(source.length+1);
  insist(sheet.includes('<dimension ref="'+range+'"/>')&&sheet.includes('<autoFilter ref="'+range+'"/>'),'XLSX worksheet range/filter mismatch');
  return {rows:source.length,netCents:net.toString(),memoIncluded:memo,orderedRowsReconciled:true,actualXlsxInspected:true};
}
export function inspectQuickBooksZIP(data,transactions){
  const entries=inspectStoredArchive(data);
  const nameOrder=[...entries.keys()].filter(x=>/^quickbooks-online-part-\d{3}\.csv$/.test(x)).sort();
  insist(nameOrder.length>=2,'Batch ZIP requires two or more QuickBooks CSV parts');
  insist(entries.size===nameOrder.length+1&&entries.has('quickbooks-csv-validation.json'),'Unexpected files in QuickBooks ZIP');
  nameOrder.forEach((name,i)=>{
    insist(name==='quickbooks-online-part-'+String(i+1).padStart(3,'0')+'.csv','QuickBooks CSV part missing or misnumbered');
  });
  const parts=nameOrder.map(name=>textValue(entries.get(name)));
  const checked=validateQuickBooksCSVParts(transactions,parts);
  let manifest;
  try{manifest=JSON.parse(textValue(entries.get('quickbooks-csv-validation.json')));}
  catch{throw Error('QuickBooks ZIP validation manifest is invalid');}
  const changedKeys=Object.keys(checked).filter(key=>!isDeepStrictEqual(manifest[key],checked[key]));
  insist(isDeepStrictEqual(manifest,checked),'QuickBooks ZIP manifest and actual CSV bytes differ: '+changedKeys.join(', '));
  insist(checked.partCount===parts.length,'QuickBooks ZIP part count differs');
  return {rows:checked.sourceRows,netCents:transactions.reduce((n,t)=>n+toMinorUnits(t.amount),0n).toString(),
    parts:parts.length,orderedRowsReconciled:true,actualZipPartsInspected:true};
}
