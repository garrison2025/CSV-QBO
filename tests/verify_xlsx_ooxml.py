"""Independent read-only XLSX OOXML/ZIP acceptance using Python stdlib.

Checks a synthetic fixture generated by the JavaScript workbook writer. This
is a structural and value-level compatibility gate, not Microsoft Excel UAT.
"""
import sys
import zipfile
from decimal import Decimal
from pathlib import Path
from xml.etree import ElementTree as ET

NS = {"x": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def verify(path):
    assert Path(path).is_file(), "Fixture workbook is missing"
    with zipfile.ZipFile(path) as archive:
        assert archive.testzip() is None, "ZIP CRC validation failed"
        names = set(archive.namelist())
        assert {
            "xl/workbook.xml",
            "xl/worksheets/sheet1.xml",
            "xl/styles.xml",
            "[Content_Types].xml",
        }.issubset(names)
        sheet = ET.fromstring(archive.read("xl/worksheets/sheet1.xml"))
        styles = ET.fromstring(archive.read("xl/styles.xml"))
        workbook = ET.fromstring(archive.read("xl/workbook.xml"))

    cells = {c.attrib["r"]: c for c in sheet.findall(".//x:sheetData/x:row/x:c", NS)}

    def value(ref):
        return cells[ref].find("x:v", NS).text

    def inline_text(ref):
        assert cells[ref].attrib["t"] == "inlineStr"
        return cells[ref].find("x:is/x:t", NS).text

    assert [value(ref) for ref in ("A2", "A3", "A4")] == ["46330", "59", "61"]
    assert [cells[ref].attrib["s"] for ref in ("A2", "A3", "A4")] == ["2"] * 3
    assert [cells[ref].attrib["s"] for ref in ("C2", "C3", "C4")] == ["1"] * 3
    assert [Decimal(value(ref)) for ref in ("C2", "C3", "C4")] == [
        Decimal("-0.01"), Decimal("9999999999999.99"), Decimal("0.01")
    ]
    assert inline_text("D2") == "000123"
    assert inline_text("B2") == '=SUM(1,2) & <tag>\r\nsecond'
    assert not sheet.findall(".//x:f", NS), "Formula-looking payee must remain inert text"

    number_formats = {
        f.attrib["numFmtId"]: f.attrib["formatCode"]
        for f in styles.findall(".//x:numFmt", NS)
    }
    assert number_formats["164"] == "yyyy-mm-dd"
    xfs = styles.find("x:cellXfs", NS)
    assert len(xfs) == 3
    assert xfs[1].attrib["numFmtId"] == "2"
    assert xfs[2].attrib["numFmtId"] == "164"
    assert sheet.find(".//x:pane", NS).attrib["state"] == "frozen"
    assert sheet.find("x:autoFilter", NS).attrib["ref"] == "A1:D4"
    assert workbook.find("x:workbookPr", NS).attrib["date1904"] == "0"
    print("PASS: independent Python OOXML/ZIP and numeric date/money/text verification")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python3 tests/verify_xlsx_ooxml.py <synthetic.xlsx>")
    verify(sys.argv[1])
